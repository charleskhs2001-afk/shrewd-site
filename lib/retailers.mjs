export const RETAILERS = LIST.map(([name, ...domains]) => ({ name, domains }));

const norm = (s) =>
  String(s || '')
    .toLowerCase()
    .replace(/&amp;|&/g, 'and')
    .replace(/\b(uk|gb|ltd|limited|partners|online|official|store|shop)\b/g, ' ')
    .replace(/\.(co\.uk|com|net)\b/g, ' ')
    .replace(/[^a-z0-9]+/g, '');

const BY_NAME = new Map(RETAILERS.map((r) => [norm(r.name), r]));

export function retailerForUrl(url) {
  let host;
  try { host = new URL(url).hostname.toLowerCase(); } catch { return null; }
  for (const r of RETAILERS) {
    if (r.domains.some((d) => host === d || host.endsWith('.' + d))) return r;
  }
  return null;
}

export function isBlocked(url) {
  let host;
  try { host = new URL(url).hostname.toLowerCase(); } catch { return true; }
  return BLOCKED.some((b) => host.includes(b));
}

const tidyName = (s) => String(s || '').replace(/\s+/g, ' ').trim();

// Decides whether an offer may be shown, and how its seller is described.
//   established: on our hand-checked list of UK retailers.
//   verified:    not on the list, but the search engine's advertiser scheme has verified
//                the seller's identity and lists it as located in the United Kingdom.
// Anything else, and anything on the blocked list, is never shown.
export function classifySeller(url, { seller, advertiser } = {}, { allowVerified = true } = {}) {
  const known = retailerForUrl(url);
  if (known) return { name: known.name, tier: 'established', key: known.name };
  if (!allowVerified || isBlocked(url)) return null;
  if (!advertiser || !advertiser.verified) return null;
  if (!/^(united kingdom|uk|great britain|england|scotland|wales|northern ireland)$/i.test(tidyName(advertiser.location))) return null;
  let host;
  try { host = new URL(url).hostname.toLowerCase().replace(/^www\./, ''); } catch { return null; }
  const name = tidyName(seller) && !/[0-9a-f]{6,}/i.test(seller) ? tidyName(seller) : host;
  return { name, tier: 'verified', key: host, company: tidyName(advertiser.name) || null };
}

// Used only to decide which products are worth a closer look; the link check above is
// what actually decides whether an offer is shown.
export function retailerForName(name) {
  const n = norm(name);
  if (!n) return null;
  return BY_NAME.get(n) || null;
}
